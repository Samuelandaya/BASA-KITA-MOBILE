// Turns the website's story, vocabulary and flashcard data into Kotlin for the Android app,
// so the website and the app share one source.
// Run from this kotlin-android folder, with the website repo (Samuelandaya/BASA-KITA) checked out next to it:
//   node tools/gen-kotlin-data.mjs ../../BASA-KITA
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const web = resolve(process.argv[2] ?? '../../BASA-KITA');

// stories.js imports image files; swap those imports for the app's asset paths.
const assetFor = {
  squirrelCover: 'images/story-squirrel-large.png', treeCover: 'images/story-tree.png',
  miaCover: 'covers/mia-red-ball.svg', puppyCover: 'covers/lost-puppy.svg',
  kiteCover: 'covers/magic-kite.svg', catDogCover: 'covers/cat-and-dog.svg',
};
let js = readFileSync(join(web, 'src/data/stories.js'), 'utf8').replace(/^import (\w+) from '[^']+';$/gm, (_, n) => `const ${n} = '${assetFor[n]}';`);
const tmp = join(tmpdir(), 'basa-stories-kt.mjs');
writeFileSync(tmp, js);
const { STORIES, LESSONS, storyQuestions } = await import(pathToFileURL(tmp).href);
const { VOCAB } = await import(pathToFileURL(join(web, 'src/data/vocabulary.js')).href);
const { DECKS } = await import(pathToFileURL(join(web, 'src/data/flashcards.js')).href);

const q = (s) => JSON.stringify(String(s)).replace(/\$/g, '\\$');
const hex = (c) => `0xFF${c.replace('#', '').toUpperCase()}`;
const list = (arr, f) => `listOf(${arr.map(f).join(', ')})`;
const quiz = (z) => `Quiz(${q(z.question)}, ${list(z.options, (o) => `QuizOption(${q(o.label)}, ${hex(o.color)}, ${o.correct ? 'true' : 'false'})`)})`;

let out = `// GENERATED by tools/gen-kotlin-data.mjs from the web app's data. Do not edit by hand.\npackage ph.basakita.app.data\n\n`;
out += `val stories: List<Story> = listOf(\n${STORIES.map((s) => `    Story(
        id = ${q(s.id)}, title = ${q(s.title)}, language = ${q(s.language)}, lang = ${q(s.lang)}, level = ${q(s.level)},
        minutes = ${s.minutes}, ages = ${q(s.ages)}, theme = ${q(s.theme)}, color = ${hex(s.color)}, cover = ${q(s.cover)},
        summary = ${q(s.summary)}, blurb = ${q(s.blurb)},
        focus = Focus(letter = ${q(s.focus.letter)}, sound = ${q(s.focus.sound)}, example = ${q(s.focus.example)}, exampleFil = ${q(s.focus.exampleFil)}, syllables = ${list(s.focus.syllables, q)}, parts = ${list(s.focus.parts, q)}, partsFil = ${list(s.focus.partsFil, q)}),
        pages = ${list(s.pages, (p) => `StoryPage(${q(p.text)}, ${q(p.word)})`)},
        questions = ${list(storyQuestions(s), quiz)},
    ),`).join('\n')}\n)\n\n`;
out += `val lessons: List<Lesson> = ${list(LESSONS, (l) => `Lesson(${l.id}, ${q(l.letter)}, ${q(l.fil)}, ${q(l.eng)})`)}\n\n`;
out += `val vocab: Map<String, VocabEntry> = mapOf(\n${Object.entries(VOCAB).map(([k, v]) => `    ${q(k)} to VocabEntry(${q(v.pair)}, ${q(v.meaning)}),`).join('\n')}\n)\n\n`;
out += `val decks: List<Deck> = listOf(\n${DECKS.map((d) => `    Deck(${q(d.letter)}, ${list(d.cards, (c) => `FlashCard(fil = ${q(c.fil)}, shape = ${q(c.shape)}, eng = ${q(c.eng)}, syl = ${list(c.syl, q)}, color = ${hex(c.color)})`)}),`).join('\n')}\n)\n`;
const dir = 'app/src/main/java/ph/basakita/app/data';
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/Content.kt`, out);
console.log('stories', STORIES.length, 'lessons', LESSONS.length, 'vocab', Object.keys(VOCAB).length, 'decks', DECKS.length);
